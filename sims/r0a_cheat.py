# Один из A,B профи (50/50). A защищён (шпаргалка) -> всегда сдаёт.
# Профи всегда сдаёт; незащищённый дилетант проваливается с вер. f.
import random
random.seed(7)
N = 10**6
for f in (1.0, 0.9, 0.5, 0.2):
    c = h = 0
    for _ in range(N//2):
        proB = random.random() < 0.5
        passB = proB or (random.random() >= f)
        if passB: c += 1; h += proB    # A сдаёт всегда
    print("f=%.1f: P(B профи|оба сдали) exact=1/(2-f)=%.4f MC=%.4f" % (f, 1/(2-f), h/c))
